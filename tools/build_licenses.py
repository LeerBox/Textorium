"""Assemble THIRD_PARTY_LICENSES.txt from the original license files (no hand transcription)."""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TP = ROOT / "third_party"


def section(title: str, body: str) -> str:
    return f"\n{'=' * 78}\n{title}\n{'=' * 78}\n{body.strip()}\n"


def main() -> None:
    m = json.loads((ROOT / "FONT_MANIFEST.json").read_text(encoding="utf-8"))
    c = m["counts"]
    out = [f"""LeerBox Text Art Studio 3.0 — Third-party notices
Generated by tools/build_licenses.py

Bundled font data (see FONT_MANIFEST.json for per-font source, author and license):
  * {c['genuineFigletToilet']} genuine FIGlet/TOIlet fonts ({c['clearLicense']} with explicit redistribution terms,
    {c['unstatedLicense']} community fonts whose license is unstated)
  * {c['arabicRaster']} Arabic bitmap fonts rasterized from SIL OFL 1.1 typefaces
  * {c['rasterTypography']} raster typography designs carried over from LeerBox V2 (rasterized from OFL / Bitstream Vera typefaces)
  * DejaVu Sans Mono / DejaVu Sans (export rendering)

LICENSE STATUS OF COMMUNITY FIGLET FONTS
Most FIGlet fonts were published in the 1990s without an explicit license. pyfiglet
(MIT) and figlet.js (MIT) redistribute them; pyfiglet states that it separates fonts
with a clear redistribution license (fonts-standard) from the others (fonts-contrib)
and that it believes legal constraints on the latter have expired. LeerBox marks every
such font with licenseTier "unstated". To ship only fonts with explicit terms, rebuild:
    python tools/build_fonts.py --license-tier clear
The font files are embedded unmodified (including their original comment headers,
which carry authorship and any permission statements).
"""]
    out.append(section("pyfiglet (font collection source) — MIT License", (TP / "pwaller_pyfiglet" / "LICENSE").read_text(encoding="utf-8")))
    out.append(section("figlet.js (font collection source) — MIT License", (TP / "patorjk_figlet.js" / "LICENSE.txt").read_text(encoding="utf-8")))
    big = (TP / "pwaller_pyfiglet" / "pyfiglet" / "fonts-standard" / "big.flf").read_text(encoding="latin-1").split("\n")
    start = next(i for i, ln in enumerate(big) if "Copyright" in ln or "copyright" in ln)
    end = next(i for i, ln in enumerate(big) if "POSSIBILITY OF SUCH DAMAGE" in ln)
    out.append(section("FIGlet standard font distribution — BSD 3-Clause (as stated in the font headers)", "\n".join(big[start:end + 1])))
    out.append(section("TOIlet fonts (cacalabs/toilet) — WTFPL v2", (TP / "cacalabs_toilet" / "COPYING").read_text(encoding="utf-8")))
    ofl_dir = TP / "arabic_fonts"
    copyrights = []
    for f in sorted(ofl_dir.glob("OFL_*.txt")):
        first = f.read_text(encoding="utf-8").splitlines()[0]
        copyrights.append(f"{f.stem.replace('OFL_', '')}: {first}")
    ofl = (ofl_dir / "OFL_amiri.txt").read_text(encoding="utf-8")
    ofl_body = ofl[ofl.index("This Font Software is licensed"):]
    out.append(section("Arabic typefaces (Amiri, Noto Naskh/Kufi/Sans Arabic, Vazirmatn) — SIL Open Font License 1.1",
                       "\n".join(copyrights) + "\n\n" + ofl_body))
    out.append(section("DejaVu fonts — Bitstream Vera / Arev license (DejaVu changes are public domain)",
                       (TP / "mono_font" / "LICENSE").read_text(encoding="utf-8")))
    v2 = (ROOT / "legacy_v2" / "LeerBox_Text_Art_Studio_V2.py").read_text(encoding="utf-8")
    mm = re.search(r"FONT_NOTICES='((?:[^'\\]|\\.)*)'", v2)
    if mm:
        notices = mm.group(1).encode("utf-8").decode("unicode_escape").encode("latin-1").decode("utf-8", "replace")
        out.append(section("Raster typography carried over from LeerBox V2 (Noto, Lato, DejaVu, Liberation) — notices shipped with V2", notices))
    out.append(section("Reference implementations used only for testing (not bundled)",
                       "pyfiglet 1.0.4 (MIT) — golden FIGlet output\npython-bidi (LGPL-3.0) and arabic-reshaper (MIT) — optional bidi/shaping cross-checks\n"
                       "Pillow (MIT-CMU / HPND) — optional runtime dependency; bundled in the Windows EXE\n"
                       "PyInstaller (GPL-2.0 with bootloader exception) — EXE packaging"))
    (ROOT / "THIRD_PARTY_LICENSES.txt").write_text("".join(out), encoding="utf-8")
    print("wrote THIRD_PARTY_LICENSES.txt", sum(len(x) for x in out), "chars")


if __name__ == "__main__":
    main()
