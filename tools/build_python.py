"""Bundle the modular package into the standalone LeerBox_Text_Art_Studio_V3.py.

The modules are concatenated in dependency order. Intra-package imports are
removed (aliases become assignments) and bundled resources are embedded as
base64 strings in ``EMBEDDED_RESOURCES``. A collision check guarantees that no
two modules define the same top-level name.
"""
from __future__ import annotations

import ast
import base64
import re
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG = ROOT / "src" / "leerbox"
OUT = ROOT / "LeerBox_Text_Art_Studio_V3.py"

MODULES = ["resources", "figlet", "arabic", "art", "effects", "raster", "fontdb", "textart", "unicode_styles",
           "imageart", "export", "project", "imgcore", "imgglyphs", "imgmodes", "imganalysis", "imganim", "smart", "cli",
           "ui/image_ws", "ui/app"]
RESOURCES = ["fontpack.bin", "arabic_tables.json", "mono_atlas.json", "glyph_masks.json", "DejaVuSansMono.ttf.z",
             "DejaVuSans.ttf.z"]

REL_IMPORT = re.compile(r"^(\s*)from \.+[\w.]* import (.+)$")


def strip_module(name: str, src: str) -> str:
    out = []
    lines = src.split("\n")
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.strip() == "from __future__ import annotations":
            i += 1
            continue
        m = REL_IMPORT.match(ln)
        if m:
            indent, names = m.group(1), m.group(2)
            if names.strip().startswith("("):
                while not names.rstrip().endswith(")"):
                    i += 1
                    names += " " + lines[i].strip()
                names = names.strip()[1:-1]
            stmts = []
            for part in names.split(","):
                part = part.split("#")[0].strip()
                if not part:
                    continue
                if " as " in part:
                    src_name, alias = [x.strip() for x in part.split(" as ")]
                    if src_name != alias:
                        stmts.append(f"{alias} = {src_name}")
            if indent:
                out.append(indent + ("; ".join(stmts) if stmts else "pass") + "  # bundled import")
            else:
                out.extend(stmts)
            i += 1
            continue
        out.append(ln)
        i += 1
    return "\n".join(out)


def top_level_names(src: str) -> set[str]:
    tree = ast.parse(src)
    names = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    names.add(t.id)
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.add(node.target.id)
    return names


def main() -> None:
    seen: dict[str, str] = {}
    parts = []
    shared_ok = {"LOG"}  # identical definitions allowed
    for mod in MODULES:
        src = (PKG / f"{mod}.py").read_text(encoding="utf-8")
        body = strip_module(mod, src)
        for n in top_level_names(body):
            if n in seen and n not in shared_ok and not n.startswith("__"):
                raise SystemExit(f"name collision: {n!r} defined in {seen[n]} and {mod}")
            seen[n] = mod
        parts.append(f"\n# {'=' * 74}\n# module: leerbox/{mod}.py\n# {'=' * 74}\n{body}")
        if mod == "resources":
            res = []
            for r in RESOURCES:
                data = (PKG / "data" / r).read_bytes()
                b64 = base64.b64encode(zlib.compress(data, 9)).decode("ascii")
                res.append(f"EMBEDDED_RESOURCES[{r!r}] = (\n" + "\n".join(
                    f"    {b64[i:i + 4000]!r}" for i in range(0, len(b64), 4000)) + "\n)")
            parts.append("\n".join(res))
    version = re.search(r'__version__ = "([^"]+)"', (PKG / "__init__.py").read_text()).group(1)
    header = f'''#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""LeerBox Text Art Studio {version} — Ultimate Edition (standalone single-file build).

Generated by tools/build_python.py from the modular sources in src/leerbox/.
Do not edit by hand — edit the modules and rebuild.

Run:  python LeerBox_Text_Art_Studio_V3.py            (desktop app, Python 3.10+, Tk)
      python LeerBox_Text_Art_Studio_V3.py --help     (headless CLI)
Optional: pip install pillow numpy  (graphic preview, raster export, Image & Animation Studio)

Bundled font data: see FONT_MANIFEST.json and THIRD_PARTY_LICENSES.txt.
"""
from __future__ import annotations
'''
    footer = '''

if __name__ == "__main__":
    if len(sys.argv) > 1:
        raise SystemExit(run_cli(sys.argv[1:]))
    main()
'''
    body = "\n".join(parts)
    # the app module ends with its own __main__ guard; remove it (the footer dispatches GUI vs CLI)
    body = body.replace('\nif __name__ == "__main__":\n    main()\n', "\n")
    code = header + body + footer
    ast.parse(code)  # syntax check
    OUT.write_text(code, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {len(code.encode('utf-8')):,} bytes, {len(seen)} top-level names")


if __name__ == "__main__":
    main()
